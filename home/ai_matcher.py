def _keyword_pattern(keyword) :
    """
    برای کلمات تک‌بخشی (بدون فاصله) با طول ۴ حرف یا بیشتر، فقط مرز شروع کلمه
    رو چک می‌کنیم (نه پایانش) تا پسوندهای مالکیت/جمع فارسی («کارفرمام»،
    «مغازمو») هم شناسایی بشن. برای عبارات چندکلمه‌ای، تطبیق دقیق با مرز
    کامل انجام میشه تا از تطبیق‌های نادرست جلوگیری بشه.
    """
    escaped = re.escape(keyword)
    if ' ' not in keyword and len(keyword) >= 4 :
        return r'\b' + escaped
    return r'\b' + escaped + r'\b'


def _normalize(text) :
    """نرمال‌سازی متن فارسی: یکسان‌سازی حروف عربی/فارسی و حذف اِعراب و علائم اضافی"""
    text = text.replace('ي', 'ی').replace('ك', 'ک')
    # حذف اعراب فارسی/عربی
    text = re.sub(r'[\u064B-\u065F\u0670]', '', text)
    # یکسان‌سازی فاصله‌ها
    text = re.sub(r'\s+', ' ', text)
    return text.strip()


def analyze_legal_query(description, valid_specialties, valid_cities) :
    """
    توضیح مشکل کاربر رو با تطبیق کلمات کلیدی تحلیل می‌کنه و دیکشنری برمی‌گردونه:
    {'specialties': [...], 'city': str|None, 'summary': str}

    این نسخه کاملاً محلی و رایگانه، هیچ فراخوانی شبکه‌ای نداره.
    """
    if not description or not description.strip() :
        raise AIMatcherError("توضیح مشکل نمی‌تواند خالی باشد.")

    description = description.strip()[:MAX_DESCRIPTION_LENGTH]
    normalized = _normalize(description)

    # ---------- تشخیص شهر (تطبیق با مرز کلمه) ----------
    detected_city = None
    for city_name in valid_cities :
        pattern = _keyword_pattern(_normalize(city_name))
        if re.search(pattern, normalized) :
            detected_city = city_name
            break

    # ---------- امتیازدهی تخصص‌ها بر اساس تعداد کلمه‌ی کلیدی مچ‌شده ----------
    scores = {}
    for specialty_name in valid_specialties :
        keywords = SPECIALTY_KEYWORDS.get(specialty_name, [])
        score = 0
        for kw in keywords :
            pattern = _keyword_pattern(_normalize(kw))
            if re.search(pattern, normalized) :
                score += 1
        if score > 0 :
            scores[specialty_name] = score

    # مرتب‌سازی بر اساس بیشترین امتیاز و برداشتن چندتای اول
    sorted_specialties = sorted(scores.keys(), key=lambda s : scores[s], reverse=True)
    matched_specialties = sorted_specialties[:MAX_MATCHED_SPECIALTIES]

    if not matched_specialties :
        return {
            'specialties' : [],
            'city' : detected_city,
            'summary' : 'متوجه ارتباط توضیح شما با تخصص‌های موجود در سایت نشدیم. لطفاً کمی واضح‌تر توضیح دهید یا مستقیماً از لیست تخصص‌ها انتخاب کنید.',
        }

    # ساخت خلاصه از روی توضیح‌های از پیش نوشته‌شده‌ی هر تخصص مچ‌شده
    summary_parts = [SPECIALTY_SUMMARIES.get(s, '') for s in matched_specialties]
    summary_parts = [p for p in summary_parts if p]
    summary = ' '.join(summary_parts)

    return {
        'specialties' : matched_specialties,
        'city' : detected_city,
        'summary' : summary,
    }
